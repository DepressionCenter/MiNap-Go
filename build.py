def build_service_worker(app_file_names):
    # app_file_names isn't used yet. It's threaded through now so a hash-based cache name and
    # a precache list can be derived from the actual packaged app/ files later, without
    # changing this function's signature (architecture.md §16.3).
    # TODO: add install/activate caching once the standalone build is wired to install at all.
    header = synth_header(
        'js', 'sw.js',
        'Service worker placeholder for the standalone build. Not registered by app/index.html yet.',
        SW_AUTHOR, SW_CREATED, SW_MODIFIED,
        "build_service_worker() in build.py (no single src/ file backs this one)")
    body = (
        "// Intentionally inert: no caching logic, and nothing in app/ registers this worker\n"
        "// yet. Kept as its own file because a service worker's scope is fixed to the URL\n"
        "// it is served from, so it cannot be merged with another script.\n"
    )
    return header + body


### Write / check ###

def write_all(target_dir, files):
    for name, content in files.items():
        path = target_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(content)


def check(target_dir, files):
    ok = True
    on_disk = {}
    if target_dir.exists():
        for p in target_dir.rglob('*'):
            if p.is_file():
                on_disk[str(p.relative_to(target_dir)).replace('\\', '/')] = read(p)
    expected = {k.replace('\\', '/'): v for k, v in files.items()}
    for name in sorted(set(expected) | set(on_disk)):
        if name not in on_disk:
            print('MISSING on disk: %s/%s' % (target_dir.name, name))
            ok = False
        elif name not in expected:
            print('EXTRA on disk (not produced by build.py): %s/%s' % (target_dir.name, name))
            ok = False
        elif on_disk[name] != expected[name]:
            print('MISMATCH: %s/%s' % (target_dir.name, name))
            ok = False
    return ok


def main():
    gas_files = build_gas()
    app_files = build_app()

    if '--check' in sys.argv:
        ok_gas = check(GAS_DIR, gas_files)
        ok_app = check(APP_DIR, app_files)
        if ok_gas and ok_app:
            print('OK: gas/ and app/ match src/.')
            sys.exit(0)
        sys.exit(1)

    write_all(GAS_DIR, gas_files)
    write_all(APP_DIR, app_files)
    print('Wrote %d files to gas/, %d files to app/.' % (len(gas_files), len(app_files)))


if __name__ == '__main__':
    main()
